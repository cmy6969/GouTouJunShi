package com.goutou.junshi.answer;

import org.json.JSONArray;
import org.json.JSONObject;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import com.goutou.junshi.core.Cfg;
import com.goutou.junshi.core.Logx;
import com.goutou.junshi.core.Self;
import com.goutou.junshi.core.Ui;

/**
 * Answering engine.
 *
 * <p>Flow per page: inject the probe, ask it whether the page holds questions, extract them, resolve
 * every question through {@link Bank}, show the result on the overlay, and — when automatic filling
 * is enabled — write the answers back into the page and read the page state again to verify the
 * write before advancing.</p>
 *
 * <p>All asynchronous steps are expressed as small named {@link Runnable} / {@link WebRef.JsResult}
 * implementations instead of nested anonymous classes; it keeps the control flow readable and the
 * generated bytecode shallow.</p>
 */
public final class Engine {

    private static final long THROTTLE_MS = 1500L;
    private static final Map<Integer, Long> LAST_OP = new HashMap<>();

    /** Single background worker: question bank requests never run on the UI thread. */
    private static final java.util.concurrent.ExecutorService IO =
            java.util.concurrent.Executors.newSingleThreadExecutor(new java.util.concurrent.ThreadFactory() {
                @Override
                public Thread newThread(Runnable r) {
                    Thread t = new Thread(r, "lumen-answer");
                    t.setDaemon(true);
                    return t;
                }
            });

    private static volatile String stealthJs;
    private static volatile String probeJs;

    /** Last WebView that showed a page; the floating button operates on it. */
    private static volatile java.lang.ref.WeakReference<Object> lastWeb = new java.lang.ref.WeakReference<>(null);
    /** Runtime override of the "fill automatically" switch, toggled by a long press on the ball. */
    private static volatile boolean autoFillOverride;
    /** Runtime override of the answering mode: 1 = automatic, -1 = manual, 0 = follow config. */
    private static volatile int modeOverride;

    private Engine() {
    }

    public static WebRef currentWebView() {
        Object raw = lastWeb.get();
        return raw == null ? null : WebRef.of(raw);
    }

    /**
     * Dumps the current question block to the log (chunked, so logcat does not cut it).
     *
     * <p>Reachable without any config by tapping the floating button three times quickly: that is how
     * a page whose DOM differs from the known ones gets diagnosed on a real device.</p>
     */
    public static void dumpCurrentPage() {
        WebRef web = currentWebView();
        if (web == null) {
            Logx.i("dom: no web view on this page");
            return;
        }
        Logx.i("dom: ---- page structure ----");
        web.eval(Js.DUMP, new WebRef.JsResult() {
            @Override
            public void onValue(String value) {
                String text = value == null ? "" : value;
                if (text.length() > 1 && text.startsWith("\"") && text.endsWith("\"")) {
                    text = text.substring(1, text.length() - 1);
                }
                int step = 900;
                for (int i = 0; i < text.length(); i += step) {
                    int end = Math.min(text.length(), i + step);
                    Logx.i("dom[" + (i / step + 1) + "] " + text.substring(i, end));
                }
                Logx.i("dom: ---- end (" + text.length() + " chars) ----");
            }
        });
    }

    static boolean autoFill() {
        return autoFillOverride || Cfg.get().autoFill;
    }

    /**
     * Effective answering mode: {@code true} = answer detected questions automatically,
     * {@code false} = do nothing until the floating button is tapped.
     *
     * <p>The runtime override (long press on the button) wins over the saved config so the user can
     * switch per page without opening the settings screen.</p>
     */
    public static boolean isAutoMode() {
        int o = modeOverride;
        if (o != 0) {
            return o > 0;
        }
        return Cfg.get().isAutoMode();
    }

    /** Flips auto/manual at runtime, persists it and returns the new state ({@code true} = auto). */
    public static boolean toggleMode() {
        boolean auto = !isAutoMode();
        modeOverride = auto ? 1 : -1;
        // Remember it in the configuration as well: a memory-only flag made the settings screen show
        // the old mode and lost the change on restart.
        Cfg.setAnswerValue("mode", auto ? "auto" : "manual");
        return auto;
    }

    /** Drops runtime overrides so a freshly pushed config takes effect immediately. */
    public static void resetOverrides() {
        autoFillOverride = false;
        modeOverride = 0;
    }

    /** Current mode override for the config dump: 1 = auto, -1 = manual, 0 = follow the config. */
    public static int modeOverrideForConfig() {
        return modeOverride;
    }

    /** Called when a WebView finished loading a page. */
    public static void onPage(Object webView, String url) {
        Cfg.Snapshot cfg = Cfg.get();
        if (!cfg.answer || webView == null) {
            return;
        }
        if (url == null || url.startsWith("javascript:") || url.startsWith("data:")
                || url.startsWith("about:") || url.startsWith("file:")) {
            return;
        }
        WebRef web = WebRef.of(webView);
        if (web == null) {
            return;
        }
        lastWeb = new java.lang.ref.WeakReference<>(webView);
        if (!isAutoMode()) {
            // Manual mode: keep the page anti-detection script running, but stay quiet until the
            // user taps the button — no probing, no lookups, no filling.
            String stealth = stealthScript(cfg);
            if (stealth != null && cfg.stealthJs) {
                web.eval(stealth, null);
            }
            Logx.i("answer: manual mode, page loaded and left untouched");
            return;
        }
        requestScan(web, true);
    }

    /** Entry point of the floating button / manual search. */
    public static void scanCurrent(WebRef web) {
        requestScan(web, false);
    }

    private static void requestScan(final WebRef web, final boolean auto) {
        int id = web.id();
        long now = System.currentTimeMillis();
        synchronized (LAST_OP) {
            Long last = LAST_OP.get(id);
            if (last != null && now - last < THROTTLE_MS) {
                return;
            }
            LAST_OP.put(id, now);
            if (LAST_OP.size() > 64) {
                LAST_OP.clear();
            }
        }
        Cfg.Snapshot cfg = Cfg.get();
        String stealth = stealthScript(cfg);
        if (stealth != null) {
            web.eval(stealth, null);
        }
        String probe = probeScript();
        if (probe == null) {
            Logx.w("answer: probe asset unavailable");
            return;
        }
        web.eval(probe, null);
        Ui.later(new StartScan(web, auto), 600L);
    }

    /** Writes the scan result to the log; also the only place stems are visible outside the UI. */
    private static void logQuestions(List<Question> questions) {
        if (questions.isEmpty()) {
            return;
        }
        StringBuilder sb = new StringBuilder("answer: page questions\n");
        int limit = Math.min(questions.size(), 30);
        for (int i = 0; i < limit; i++) {
            Question q = questions.get(i);
            sb.append("  ").append(q.describe()).append('\n');
        }
        Logx.i(sb.toString());
    }

    private static void handleScan(final WebRef web, String json, final boolean auto) {
        final java.util.List<Question> questions = parse(json);
        if (questions.isEmpty()) {
            Ball.miss();
            if (!auto) {
                Ui.toast("Lumen：没有解析到题目");
            }
            return;
        }
        Logx.i("answer: " + questions.size() + " question(s) on page");
        logQuestions(questions);
        if (Cfg.get().debugDump) {
            web.eval(Js.DUMP, new Dumped());
        }
        final Cfg.Snapshot cfg = Cfg.get();
        if (!cfg.bankAnswer && !cfg.aiOn && !VisionBank.configured(cfg)) {
            // Both sources are off: only extraction was asked for.
            StringBuilder sb = new StringBuilder("题库与 AI 都已关闭（设置里可开启）：");
            int limit = Math.min(questions.size(), 2);
            for (int i = 0; i < limit; i++) {
                Question q = questions.get(i);
                if (i > 0) {
                    sb.append("；");
                }
                sb.append(q.id).append(' ').append(shorten(q.stem, 16));
            }
            if (questions.size() > limit) {
                sb.append("…共 ").append(questions.size()).append(" 道");
            }
            Ui.toastLong(sb.toString());
            Ball.idle();
            Logx.i("answer: banks and AI are off, extracted " + questions.size()
                    + " question(s), no query");
            return;
        }
        Ball.busy();
        IO.execute(new ResolveTask(web, questions, auto, cfg));
    }

    /** Resolves every question off the UI thread, then publishes the result back on it. */
    private static final class ResolveTask implements Runnable {
        private final WebRef web;
        private final java.util.List<Question> questions;
        private final boolean auto;
        private final Cfg.Snapshot cfg;

        ResolveTask(WebRef web, java.util.List<Question> questions, boolean auto, Cfg.Snapshot cfg) {
            this.web = web;
            this.questions = questions;
            this.auto = auto;
            this.cfg = cfg;
        }

        @Override
        public void run() {
            int found = 0;
            StringBuilder report = new StringBuilder();
            boolean visionReady = VisionBank.configured(cfg);
            for (int index = 0; index < questions.size(); index++) {
                Question q = questions.get(index);
                if (q.hasImage && visionReady) {
                    // Picture question: hand the whole thing (stem + options, stitched across
                    // screens) to the vision model instead of trying to describe it as text.
                    String shot = Shot.captureBlocking(web, index, 12000L);
                    if (shot == null) {
                        Logx.w("vision: screenshot failed for " + q.id);
                    } else {
                        VisionBank.Hit v = VisionBank.query(shot, q, cfg);
                        if (!v.answer.isEmpty()) {
                            String wire = Norm.forType(q.type, v.answer);
                            if (!wire.isEmpty()) {
                                q.answer = wire;
                                q.source = "截图";
                                found++;
                                report.append(q.id).append(". ").append(shorten(q.stem, 24))
                                        .append(" → [截图] ").append(wire).append('\n');
                                Logx.i("vision: answered " + q.id + " = " + wire);
                                continue;
                            }
                        }
                        Logx.w("vision: miss " + q.id + " :: " + v.note);
                    }
                }
                Bank.Result r;
                try {
                    r = Bank.lookup(q, cfg);
                } catch (Throwable t) {
                    Logx.e("answer: lookup failed", t);
                    r = null;
                }
                if (r == null) {
                    report.append(q.id).append(". ").append(shorten(q.stem, 24)).append(" → 未命中\n");
                    continue;
                }
                if (r.answer.isEmpty()) {
                    report.append(q.id).append(". ").append(shorten(q.stem, 24)).append(" → 未命中")
                            .append(r.note.isEmpty() ? "" : ("（" + r.note + "）")).append('\n');
                    continue;
                }
                q.answer = Norm.forType(q.type, r.answer);
                q.source = r.source;
                if (q.answer.isEmpty()) {
                    report.append(q.id).append(". ").append(shorten(q.stem, 24)).append(" → 答案无效\n");
                    continue;
                }
                found++;
                report.append(q.id).append(". ").append(shorten(q.stem, 24))
                        .append(" → [").append(q.source).append("] ").append(q.answer).append('\n');
            }
            final String text = report.toString().trim();
            final int resolved = found;
            Logx.i("answer: resolved " + resolved + "/" + questions.size());
            Ui.run(new Runnable() {
                @Override
                public void run() {
                    String toast = summarize(questions, resolved);
                    if (resolved > 0) {
                        Ui.toastLong(toast);
                    } else if (!auto) {
                        Ui.toastLong(toast);
                    }
                    if (resolved > 0) {
                        Ball.busy();
                    } else {
                        Ball.miss();
                    }
                    if (autoFill() && resolved > 0) {
                        Ui.later(new FillTask(web, buildPayload(questions), cfg),
                                Math.max(200L, cfg.delayMs / 2));
                    } else if (resolved > 0) {
                        // Nothing to write: do not leave the button stuck in the "busy" colour.
                        Ball.idle();
                    }
                }
            });
        }
    }

    /** One-line summary for the toast; the full report only goes to the log. */
    private static String summarize(java.util.List<Question> questions, int resolved) {
        if (questions.size() == 1) {
            Question q = questions.get(0);
            if (q.answer == null || q.answer.isEmpty()) {
                return "未找到答案（" + questions.size() + " 题）";
            }
            return "答案：" + q.answer + "（" + q.source + "）";
        }
        StringBuilder sb = new StringBuilder();
        sb.append("已答 ").append(resolved).append('/').append(questions.size()).append("：");
        int limit = Math.min(questions.size(), 5);
        for (int i = 0; i < limit; i++) {
            Question q = questions.get(i);
            if (i > 0) {
                sb.append('、');
            }
            sb.append(q.answer == null || q.answer.isEmpty() ? "—" : q.answer);
        }
        if (questions.size() > limit) {
            sb.append('…');
        }
        return sb.toString();
    }

    // -------------------------------------------------------------- callbacks

    private static final class StartScan implements Runnable {
        private final WebRef web;
        private final boolean auto;

        StartScan(WebRef web, boolean auto) {
            this.web = web;
            this.auto = auto;
        }

        @Override
        public void run() {
            web.eval("(window.__lumen?__lumen.ping():'NONE')", new Ping(web, auto));
        }
    }

    private static final class Ping implements WebRef.JsResult {
        private final WebRef web;
        private final boolean auto;

        Ping(WebRef web, boolean auto) {
            this.web = web;
            this.auto = auto;
        }

        @Override
        public void onValue(String value) {
            String state = unquote(value);
            if (!"QUESTIONS".equals(state)) {
                Ball.miss();
                if (!auto) {
                    Ui.toast("Lumen：当前页面没有发现题目");
                }
                return;
            }
            web.eval("__lumen.scan()", new Scanned(web, auto));
        }
    }

    private static final class Scanned implements WebRef.JsResult {
        private final WebRef web;
        private final boolean auto;

        Scanned(WebRef web, boolean auto) {
            this.web = web;
            this.auto = auto;
        }

        @Override
        public void onValue(String scanned) {
            handleScan(web, unquote(scanned), auto);
        }
    }

    private static final class FillTask implements Runnable {
        private final WebRef web;
        private final String payload;
        private final Cfg.Snapshot cfg;

        FillTask(WebRef web, String payload, Cfg.Snapshot cfg) {
            this.web = web;
            this.payload = payload;
            this.cfg = cfg;
        }

        @Override
        public void run() {
            web.eval("__lumen.fill(" + JSONObject.quote(payload) + ")", new Filled(web, cfg));
        }
    }

    private static final class Filled implements WebRef.JsResult {
        private final WebRef web;
        private final Cfg.Snapshot cfg;

        Filled(WebRef web, Cfg.Snapshot cfg) {
            this.web = web;
            this.cfg = cfg;
        }

        @Override
        public void onValue(String result) {
            Logx.i("answer: fill " + unquote(result));
            Ball.idle();
            // Read the page state back after its own handlers ran; this is what actually got saved.
            Ui.later(new Runnable() {
                @Override
                public void run() {
                    web.eval("(window.__lumen?__lumen.verify():'')", new Verified());
                }
            }, 900L);
            if (cfg.autoNext) {
                Ui.later(new NextTask(web), Math.max(1200L, cfg.delayMs));
            }
        }
    }

    private static final class Verified implements WebRef.JsResult {
        @Override
        public void onValue(String value) {
            String state = unquote(value);
            if (!state.isEmpty() && !"(pending)".equals(state)) {
                Logx.i("answer: verify " + state);
            }
        }
    }

    private static final class NextTask implements Runnable {
        private final WebRef web;

        NextTask(WebRef web) {
            this.web = web;
        }

        @Override
        public void run() {
            web.eval("__lumen.next()", new NextResult());
        }
    }

    private static final class NextResult implements WebRef.JsResult {
        @Override
        public void onValue(String value) {
            Logx.i("answer: next " + unquote(value));
        }
    }

    /** Prints the structure of the current question block — used to adapt selectors to a new page. */
    private static final class Dumped implements WebRef.JsResult {
        @Override
        public void onValue(String value) {
            Logx.i("answer: DOM " + unquote(value));
        }
    }

    // ------------------------------------------------------------------ parse

    static List<Question> parse(String json) {
        List<Question> out = new ArrayList<>();
        if (json == null || json.isEmpty()) {
            return out;
        }
        try {
            JSONObject root = new JSONObject(json);
            if (root.optInt("ok", 0) != 1) {
                Logx.w("answer: scan failed " + root.optString("err"));
                return out;
            }
            JSONArray items = root.optJSONArray("items");
            if (items == null) {
                return out;
            }
            for (int i = 0; i < items.length(); i++) {
                JSONObject o = items.optJSONObject(i);
                if (o == null) {
                    continue;
                }
                Question q = new Question();
                q.id = o.optString("qid", String.valueOf(i));
                q.type = o.optInt("type", -1);
                q.stem = o.optString("stem", "").trim();
                q.blanks = o.optInt("blanks", 0);
                q.hasImage = o.optInt("img", 0) == 1;
                JSONObject box = o.optJSONObject("box");
                if (box != null) {
                    q.pageTop = box.optInt("top", 0);
                    q.pageHeight = box.optInt("h", 0);
                }
                JSONArray opts = o.optJSONArray("options");
                if (opts != null) {
                    for (int j = 0; j < opts.length(); j++) {
                        JSONObject oo = opts.optJSONObject(j);
                        if (oo == null) {
                            continue;
                        }
                        String k = oo.optString("k", "");
                        String t = oo.optString("t", "");
                        if (!k.isEmpty()) {
                            q.options.add(new Question.Option(k.toUpperCase(), t,
                                    oo.optString("src", "")));
                        }
                    }
                }
                if (!q.stem.isEmpty()) {
                    out.add(q);
                }
            }
        } catch (Throwable t) {
            Logx.e("answer parse", t);
        }
        return out;
    }

    private static String buildPayload(List<Question> questions) {
        JSONArray answers = new JSONArray();
        for (Question q : questions) {
            if (q.answer.isEmpty()) {
                continue;
            }
            JSONObject a = new JSONObject();
            try {
                a.put("qid", q.id);
                a.put("type", q.type);
                a.put("answer", q.answer);
            } catch (Throwable ignored) {
            }
            answers.put(a);
        }
        JSONObject root = new JSONObject();
        try {
            root.put("answers", answers);
        } catch (Throwable ignored) {
        }
        return root.toString();
    }

    // ------------------------------------------------------------------ utils

    private static String stealthScript(Cfg.Snapshot cfg) {
        if (!cfg.stealthJs) {
            return null;
        }
        String js = stealthJs;
        if (js == null) {
            js = Self.asset("js/stealth.js");
            stealthJs = js;
        }
        return js;
    }

    private static String probeScript() {
        String js = probeJs;
        if (js == null) {
            js = Self.asset("js/probe.js");
            probeJs = js;
        }
        return js;
    }

    /**
     * {@code evaluateJavascript} answers with a JSON encoded literal, so every string comes back
     * quoted and escaped.  Unwrap it once.
     */
    static String unquote(String value) {
        if (value == null) {
            return "";
        }
        String v = value.trim();
        if (v.isEmpty() || "null".equals(v) || "undefined".equals(v)) {
            return "";
        }
        if (v.length() >= 2 && v.charAt(0) == '"' && v.charAt(v.length() - 1) == '"') {
            try {
                return new JSONArray("[" + v + "]").getString(0);
            } catch (Throwable ignored) {
                return v.substring(1, v.length() - 1);
            }
        }
        return v;
    }

    private static String shorten(String s, int max) {
        if (s == null) {
            return "";
        }
        String v = s.replace('\n', ' ').trim();
        return v.length() <= max ? v : v.substring(0, max) + "…";
    }

    public static void reset() {
        synchronized (LAST_OP) {
            LAST_OP.clear();
        }
        Bank.clearCache();
        Ball.idle();
    }
}
